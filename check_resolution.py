CLOB = 'https://clob.polymarket.com/last-trade-price?token_id='
resolved_yes = []
resolved_no = []
still_open = []
errors = []

for tid, shares, cash, label in positions:
    try:
        result = subprocess.run(
            ['curl', '-s', '-H', 'User-Agent: Mozilla/5.0', CLOB + tid],
            capture_output=True, text=True, timeout=10
        )
        data = json.loads(result.stdout)
        price = float(data.get('price', 0.5))

        if price >= 0.95:
            payout = shares * 1.0
            pnl = cash + payout
            resolved_yes.append((label, shares, cash, pnl))
        elif price <= 0.05:
            payout = 0.0
            pnl = cash + payout
            resolved_no.append((label, shares, cash, pnl))
        else:
            still_open.append((label, shares, cash, price))
    except Exception as e:
        errors.append((label, str(e)))
    time.sleep(0.08)

print('=== RESOLVED YES (price >= 0.95) ===')
for label, shares, cash, pnl in resolved_yes:
    outcome = 'WIN' if pnl > 0 else 'LOSS'
    print(f'  {label:38s}  shares={shares:+7.2f}  cash={cash:+7.2f}  PnL={pnl:+6.2f}  [{outcome}]')

print()
print('=== RESOLVED NO (price <= 0.05) ===')
for label, shares, cash, pnl in resolved_no:
    outcome = 'WIN' if pnl > 0 else 'LOSS'
    print(f'  {label:38s}  shares={shares:+7.2f}  cash={cash:+7.2f}  PnL={pnl:+6.2f}  [{outcome}]')

print()
print('=== STILL OPEN / UNRESOLVED ===')
for label, shares, cash, price in still_open:
    mtm = cash + shares * price
    print(f'  {label:38s}  shares={shares:+7.2f}  cash={cash:+7.2f}  mid={price:.3f}  MTM={mtm:+6.2f}')

if errors:
    print()
    print('=== ERRORS ===')
    for label, err in errors:
        print(f'  {label}: {err}')

print()
total_yes_pnl = sum(pnl for _,_,_,pnl in resolved_yes)
total_no_pnl = sum(pnl for _,_,_,pnl in resolved_no)
total_res = total_yes_pnl + total_no_pnl
mtm_open = sum(cash + shares*price for _,shares,cash,price in still_open)
print(f'Resolved YES P&L: {total_yes_pnl:+.2f}')
print(f'Resolved NO  P&L: {total_no_pnl:+.2f}')
print(f'Total RESOLVED P&L:  {total_res:+.2f}')
print(f'MTM of open positions: {mtm_open:+.2f}')
print(f'Grand total (resolved + MTM): {total_res + mtm_open:+.2f}')
